# ── Chat Input & Processing ──────────────────────────────
if question := st.chat_input("Ask anything about your uploaded documents..."):

    if not st.session_state.get("indexed"):
        st.warning("⚠️ Please upload and index at least one document (.pdf, .txt, .md) first.")

    elif not os.environ.get("GROQ_API_KEY"):
        st.warning("⚠️ Please enter your Groq API Key in the sidebar to start asking questions.")

    else:
        st.session_state.messages.append({"role": "user", "content": question})
        with st.chat_message("user"):
            st.markdown(question)

        with st.chat_message("assistant"):

            query_type = classify_query(question)
            format_instructions = FORMAT_INSTRUCTIONS.get(
                query_type, FORMAT_INSTRUCTIONS["general"]
            )

            chain, retriever, history = load_qa_chain(
                st.session_state.messages,
                mode=mode,
                model_name=selected_model,
                temperature=temperature,
                top_k=top_k
            )

            response_container = st.empty()
            full_text = ""

            start_time = time.time()
            with st.spinner("Analyzing context & generating response..."):
                for chunk in chain.stream({
                    "input": question,
                    "chat_history": history,
                    "query_type": query_type,
                    "format_instructions": format_instructions,
                }):
                    if "answer" in chunk:
                        full_text += chunk["answer"]
                        response_container.markdown(full_text + "▌")

            elapsed = round(time.time() - start_time, 2)
            response_container.markdown(full_text)
            st.caption(f"⚡ Generated in {elapsed}s | Mode: {mode.capitalize()} | Intent: {query_type.capitalize()} | Model: {selected_model}")

            # ── Source Attribution & Relevance Scores ────
            if is_retrieval_needed(question):
                sources = retriever.invoke(question)

                if sources:
                    with st.expander("🔍 View Retrieved Sources & Rerank Scores"):
                        file_groups: dict = {}
                        for doc in sources:
                            raw_source = doc.metadata.get("source", "Unknown file")
                            file_name = os.path.basename(raw_source)
                            page = doc.metadata.get("page", None)
                            page_num = page + 1 if page is not None else "N/A"
                            score = doc.metadata.get("rerank_score", None)
                            snippet = doc.page_content[:250].strip().replace("\n", " ")

                            if file_name not in file_groups:
                                file_groups[file_name] = []
                            file_groups[file_name].append((page_num, score, snippet))

                        for file_name, entries in file_groups.items():
                            st.markdown(f"📄 **{file_name}**")
                            for page_num, score, snippet in entries:
                                score_label = f" | Cross-Encoder Score: `{score}`" if score is not None else ""
                                st.markdown(f"> Page {page_num}{score_label}: {snippet}...")
                            st.divider()

        st.session_state.messages.append({"role": "assistant", "content": full_text})
