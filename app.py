# ── Query Intent Filter ──────────────────────────────────
def is_retrieval_needed(query: str) -> bool:
    casual_words = [
        "hi", "hello", "hey", "thanks", "thank you",
        "ok", "okay", "bye", "cool", "great"
    ]
    return not any(word in query.lower() for word in casual_words)


# ── Query Classifier ─────────────────────────────────────
def classify_query(query: str) -> str:
    q = query.lower()
    if any(word in q for word in ["difference", "compare", "vs", "versus"]):
        return "compare"
    elif any(word in q for word in ["summarize", "summary"]):
        return "summarize"
    elif any(word in q for word in ["what is", "define", "meaning"]):
        return "definition"
    elif any(word in q for word in ["explain", "how", "why"]):
        return "explain"
    else:
        return "general"


# ── Chat Export Builder ──────────────────────────────────
def build_export_text(messages: list, indexed_files: list) -> str:
    lines = []
    lines.append("=" * 60)
    lines.append("DOCUMIND AI — CONVERSATION EXPORT")
    lines.append(f"Exported: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    lines.append(f"Indexed Documents: {', '.join(indexed_files) if indexed_files else 'None'}")
    lines.append("=" * 60)
    lines.append("")

    for msg in messages:
        role = "User" if msg["role"] == "user" else "DocuMind Assistant"
        lines.append(f"[{role}]")
        lines.append(msg["content"])
        lines.append("")

    lines.append("=" * 60)
    lines.append("Generated by DocuMind AI | Developed by Anurag Gurjar")
    return "\n".join(lines)


